// Helper to convert an AgentSkillSuite to an individual AgentSkill for compatibility
export function suiteToAgentSkill(suite: AgentSkillSuite): AgentSkill {
  return {
    id: suite.id,
    name: suite.name,
    category: suite.category,
    description: suite.description,
    path: `skills/${suite.id}`,
    entrypoint: "SKILL.md",
    package: `${suite.id}.skill`,
    execution_mode: "plan-first",
    tags: [suite.category, ...suite.skills.map((s) => s.name)],
    markdown: suite.files?.[0]?.content || `# ${suite.name}\n\n${suite.description}`,
    isOfficial: true,
    author: suite.author,
    version: suite.version,
    supportedRuntimes: ["Claude Code", "OpenAI Codex", "Manus", "Cursor", "AI Studio"],
    installed: suite.installed,
    isFavorite: suite.isFavorite,
    imageUrl: suite.imageUrl || suite.coverTheme?.imageUrl,
    cordelArt: suite.cordelArt || suite.coverTheme?.cordelArt,
    coverTheme: suite.coverTheme,
    promptSuggestions: suite.prompts,
    files: suite.files,
  };
}
